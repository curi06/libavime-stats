-- LIBAVIME Stats: temporadas y fases de competencia
-- Ejecutar una sola vez en Supabase SQL Editor antes de publicar la aplicación.
-- Los partidos existentes se conservan y se asignan a LIBAVIME 2026.
-- Por seguridad, todos quedan inicialmente como serie_regular; los partidos de finales
-- ya registrados deben reclasificarse desde Administración > Gestión de Partidos.

begin;

create table if not exists public.temporadas (
  id bigint generated by default as identity primary key,
  nombre text not null,
  anio smallint not null unique,
  estado text not null default 'en_curso',
  created_at timestamptz not null default now(),
  constraint temporadas_estado_check
    check (estado in ('en_curso', 'finalizada', 'archivada'))
);

insert into public.temporadas (nombre, anio, estado)
values ('LIBAVIME 2026', 2026, 'en_curso')
on conflict (anio) do nothing;

alter table public.partidos
  add column if not exists temporada_id bigint;

alter table public.partidos
  add column if not exists fase text not null default 'serie_regular';

do $$
begin
  alter table public.partidos
    add constraint partidos_temporada_id_fkey
    foreign key (temporada_id) references public.temporadas(id);
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  alter table public.partidos
    add constraint partidos_fase_check
    check (fase in ('serie_regular', 'finales'));
exception
  when duplicate_object then null;
end
$$;

update public.partidos p
set temporada_id = t.id
from public.temporadas t
where t.anio = 2026
  and p.temporada_id is null;

-- La final Espartanos vs. Gladiadores comenzó el 14 de noviembre de 2026.
-- Reclasificamos como finales los partidos existentes de ese cruce desde esa fecha;
-- los encuentros anteriores permanecen en serie_regular.
update public.partidos
set fase = 'finales'
where temporada_id = (select id from public.temporadas where anio = 2026)
  and fecha::date >= date '2026-11-14'
  and (
    (lower(trim(equipo_local)) = 'espartanos' and lower(trim(equipo_visitante)) = 'gladiadores')
    or
    (lower(trim(equipo_local)) = 'gladiadores' and lower(trim(equipo_visitante)) = 'espartanos')
  );

alter table public.partidos
  alter column temporada_id set not null;

create index if not exists partidos_temporada_fase_estado_idx
  on public.partidos (temporada_id, fase, estado);

-- Los nuevos partidos sin temporada explícita se asignan a la temporada activa.
create or replace function public.asignar_temporada_activa_a_partido()
returns trigger
language plpgsql
as $$
begin
  if new.temporada_id is null then
    select id
      into new.temporada_id
    from public.temporadas
    where estado = 'en_curso'
    order by anio desc
    limit 1;
  end if;

  if new.temporada_id is null then
    raise exception 'No existe una temporada activa para asignar el partido.';
  end if;

  if new.fase is null then
    new.fase := 'serie_regular';
  end if;

  return new;
end;
$$;

drop trigger if exists asignar_temporada_activa_a_partido
  on public.partidos;

create trigger asignar_temporada_activa_a_partido
before insert or update of temporada_id
on public.partidos
for each row
execute function public.asignar_temporada_activa_a_partido();

-- Las temporadas se pueden consultar públicamente; la gestión queda para usuarios autenticados.
alter table public.temporadas enable row level security;

drop policy if exists "Temporadas lectura publica" on public.temporadas;
create policy "Temporadas lectura publica"
  on public.temporadas
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Temporadas gestion autenticada" on public.temporadas;
create policy "Temporadas gestion autenticada"
  on public.temporadas
  for all
  to authenticated
  using (true)
  with check (true);

grant select on public.temporadas to anon, authenticated;
grant insert, update, delete on public.temporadas to authenticated;
grant usage, select on sequence public.temporadas_id_seq to authenticated;

comment on column public.partidos.temporada_id is
  'Temporada LIBAVIME a la que pertenece el partido.';
comment on column public.partidos.fase is
  'Fase de la temporada: serie_regular o finales.';

commit;
