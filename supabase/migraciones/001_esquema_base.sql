create table if not exists public.admin_temporadas (
  id bigint generated by default as identity primary key,
  nombre text not null,
  fecha_inicio date,
  fecha_fin date,
  activa boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_usuarios (
  id uuid primary key references auth.users (id) on delete cascade,
  nombre text not null,
  correo text not null,
  rol text not null default 'Consulta',
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  puede_planilla boolean not null default false
);

create table if not exists public.equipos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nombre text,
  slug text,
  logo text,
  color text,
  ganados bigint,
  perdidos bigint,
  color_principal text,
  color_secundario text
);

create table if not exists public.jugadores (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nombre text,
  slug text,
  numero bigint,
  posicion text,
  equipo text,
  foto text,
  ppg double precision,
  rpg double precision,
  apg double precision
);

create table if not exists public.partidos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  equipo_local text,
  fecha text,
  hora text,
  cancha text,
  puntos_local bigint,
  puntos_visitante bigint,
  estado text,
  equipo_visitante text,
  temporada_id bigint not null references public.admin_temporadas (id),
  fase text not null default 'serie_regular'
);

create table if not exists public.estadisticas_partido (
  id bigint generated by default as identity primary key,
  partido_id bigint not null references public.partidos (id) on delete cascade,
  jugador_id bigint not null references public.jugadores (id) on delete cascade,
  puntos integer not null default 0,
  asistencias integer not null default 0,
  rebotes integer not null default 0,
  created_at timestamptz not null default now(),
  estado text not null default 'jugó',
  faltas integer not null default 0,
  flagrantes integer not null default 0,
  tiros_encestados integer not null default 0,
  tiros_fallados integer not null default 0,
  unique (partido_id, jugador_id)
);

create table if not exists public.libavime_configuracion (
  clave text primary key,
  datos jsonb not null,
  actualizado_en timestamptz not null default now()
);

create table if not exists public.libavime_disenos (
  id uuid primary key default gen_random_uuid(),
  titulo text not null,
  tipo text not null default 'post',
  archivo text not null,
  url text not null,
  publicado boolean not null default false,
  creado_en timestamptz not null default now(),
  jugador text,
  categoria text,
  jornada text
);

-- Vistas de promedios (reconstruidas y verificadas contra producción)
--   calculadas: todas las filas del jugador.
--   estadisticas_jugadores: promedios solo de partidos con puntos, rebotes o
--   asistencias (misma fórmula que producción: FILTER, el jugador aparece
--   aunque todas sus filas estén en cero).
create or replace view public.estadisticas_jugadores_calculadas as
select
  e.jugador_id,
  count(*)::bigint as partidos_jugados,
  coalesce(sum(e.puntos), 0)::bigint as puntos_totales,
  coalesce(sum(e.rebotes), 0)::bigint as rebotes_totales,
  coalesce(sum(e.asistencias), 0)::bigint as asistencias_totales,
  round(avg(e.puntos), 1) as ppg,
  round(avg(e.rebotes), 1) as rpg,
  round(avg(e.asistencias), 1) as apg
from public.estadisticas_partido e
group by e.jugador_id;

create or replace view public.estadisticas_jugadores as
select
  e.jugador_id,
  round(avg(e.puntos) filter (where (coalesce(e.puntos, 0) <> 0 or coalesce(e.rebotes, 0) <> 0 or coalesce(e.asistencias, 0) <> 0)), 1) as ppg,
  round(avg(e.rebotes) filter (where (coalesce(e.puntos, 0) <> 0 or coalesce(e.rebotes, 0) <> 0 or coalesce(e.asistencias, 0) <> 0)), 1) as rpg,
  round(avg(e.asistencias) filter (where (coalesce(e.puntos, 0) <> 0 or coalesce(e.rebotes, 0) <> 0 or coalesce(e.asistencias, 0) <> 0)), 1) as apg,
  count(*) filter (where (coalesce(e.puntos, 0) <> 0 or coalesce(e.rebotes, 0) <> 0 or coalesce(e.asistencias, 0) <> 0))::bigint as partidos_jugados
from public.estadisticas_partido e
group by e.jugador_id;

-- Funciones de roles usadas por el sitio actual
create or replace function public.es_administrador()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.admin_usuarios
    where id = auth.uid() and rol = 'Administrador' and activo = true
  );
$$;

create or replace function public.usuario_puede_planilla()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.admin_usuarios
    where id = auth.uid() and activo = true and puede_planilla = true
  );
$$;

